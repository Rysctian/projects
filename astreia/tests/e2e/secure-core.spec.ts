import { expect, test } from '@playwright/test';

test('new core project completes and reopens work with a retained resolution history', async ({ page }) => {
    await page.goto('/login');
    await page.getByLabel('Email address', { exact: true }).fill('admin@astreia.test');
    await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await page.getByRole('button', { name: 'New project', exact: true }).click();
    await page.getByLabel('Code', { exact: false }).fill('E2ENEW');
    await page.getByLabel('Name', { exact: true }).fill('Secure core workspace');
    await page.getByRole('button', { name: 'Create project', exact: true }).click();
    await expect(page).toHaveURL(/\/projects\/\d+$/);
    await expect(page.getByRole('link', { name: 'Workflow', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'New ticket', exact: true }).click();
    await page.getByLabel('Summary', { exact: true }).fill('Investigate a customer lookup');
    await page.getByLabel('Description', { exact: true }).fill('Search by the customer reference.');
    await page.getByLabel('Work type', { exact: true }).selectOption({ label: 'Bug' });
    await page.getByLabel('Assignee', { exact: true }).selectOption({ label: 'Core Admin' });
    await page.getByRole('button', { name: 'Create ticket', exact: true }).click();
    await expect(page).toHaveURL(/\/tickets\/\d+$/);
    await expect(page.getByText('E2ENEW-00001', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Move ticket', exact: true }).click();
    await page.getByLabel('Allowed destination').selectOption({ label: 'In progress' });
    await page.getByRole('button', { name: 'Move to selected stage', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Move ticket', exact: true })).not.toBeVisible();
    await page.getByRole('button', { name: 'Move ticket', exact: true }).click();
    await page.getByLabel('Allowed destination').selectOption({ label: 'Resolved' });
    await page.getByLabel('Resolution', { exact: true }).selectOption({ label: 'Duplicate' });
    await page.getByLabel('Completion notes').fill('Already covered by the customer search improvement.');
    await page.getByRole('button', { name: 'Resolve ticket', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Move ticket', exact: true })).not.toBeVisible();
    await expect(page.getByText('Resolution: Duplicate')).toBeVisible();
    await page.getByRole('button', { name: 'Manage ticket', exact: true }).click();
    await page.getByLabel('Ticket action').selectOption('reopen');
    await page.getByLabel('Reason', { exact: true }).fill('Different customer reference format.');
    await page.getByRole('button', { name: 'Apply action', exact: true }).click();
    await expect(page.getByText('Open', { exact: true }).first()).toBeVisible();
    await expect(page.getByText('E2ENEW-00001', { exact: true })).toBeVisible();
    await expect(page.getByText('Already covered by the customer search improvement.').first()).toBeVisible();
});
